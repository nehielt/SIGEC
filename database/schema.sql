INSERT INTO clients (code, name)
SELECT DISTINCT split_part(BTRIM(account_code), CHR(92), 1), BTRIM(account_name)
FROM inventory_items
WHERE client_id IS NULL AND BTRIM(account_name) <> ''
ON CONFLICT (code, name) DO NOTHING;

INSERT INTO departaments (client_id, department_code)
SELECT DISTINCT c.id, SUBSTRING(BTRIM(i.account_code) FROM POSITION(CHR(92) IN BTRIM(i.account_code)) + 1)
FROM inventory_items i
JOIN clients c
  ON c.code = split_part(BTRIM(i.account_code), CHR(92), 1)
 AND c.name = BTRIM(i.account_name)
WHERE i.client_id IS NULL
  AND BTRIM(i.account_name) <> ''
  AND POSITION(CHR(92) IN BTRIM(i.account_code)) > 0
ON CONFLICT (client_id, department_code) DO NOTHING;

