    department_code VARCHAR(120) NOT NULL,
    name VARCHAR(250) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (client_id, department_code),
    UNIQUE (id, client_id)
);

