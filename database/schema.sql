CREATE TABLE IF NOT EXISTS movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio VARCHAR(40) UNIQUE,
    type VARCHAR(24) NOT NULL
        CHECK (type IN ('receive', 'transfer', 'dispatch', 'return', 'writeoff')),
    reference VARCHAR(120) NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    created_by BIGINT NOT NULL REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS movement_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_id BIGINT NOT NULL REFERENCES movements(id) ON DELETE RESTRICT,
    item_id BIGINT NOT NULL REFERENCES inventory_items(id) ON DELETE RESTRICT,
    from_location_id BIGINT REFERENCES warehouse_locations(id),
    to_location_id BIGINT REFERENCES warehouse_locations(id),
    from_status VARCHAR(24),
    to_status VARCHAR(24) NOT NULL,
    UNIQUE (movement_id, item_id)
);

