              END
          )
    ) THEN
        RAISE EXCEPTION 'No se pudieron relacionar todos los códigos de cliente del inventario con clients.';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM inventory_items i
        JOIN clients c
          ON c.code = CASE
              WHEN LENGTH(split_part(BTRIM(i.account_code), CHR(92), 1)) < 4
              THEN LPAD(split_part(BTRIM(i.account_code), CHR(92), 1), 4, CHR(48))
              ELSE split_part(BTRIM(i.account_code), CHR(92), 1)
          END
        WHERE POSITION(CHR(92) IN BTRIM(i.account_code)) > 0
          AND NOT EXISTS (
              SELECT 1
              FROM departaments d
              WHERE d.client_id = c.id
                AND d.department_code IN (
                    SUBSTRING(BTRIM(i.account_code) FROM POSITION(CHR(92) IN BTRIM(i.account_code)) + 1),
                    CASE
                        WHEN LEFT(
                            SUBSTRING(BTRIM(i.account_code) FROM POSITION(CHR(92) IN BTRIM(i.account_code)) + 1),
                            LENGTH(c.code) + 1
                        ) = c.code || '-'
                        THEN SUBSTRING(
                            SUBSTRING(BTRIM(i.account_code) FROM POSITION(CHR(92) IN BTRIM(i.account_code)) + 1)
                            FROM LENGTH(c.code) + 2
                        )
                        ELSE SUBSTRING(BTRIM(i.account_code) FROM POSITION(CHR(92) IN BTRIM(i.account_code)) + 1)
                    END
                )
          )
    ) THEN
        RAISE EXCEPTION 'No se pudieron relacionar todos los códigos de departamento del inventario con departaments.';
    END IF;
END $$;

WITH parsed AS (
    SELECT i.id,
           BTRIM(i.account_code) AS raw_code,
           CASE
               WHEN LENGTH(split_part(BTRIM(i.account_code), CHR(92), 1)) < 4
               THEN LPAD(split_part(BTRIM(i.account_code), CHR(92), 1), 4, CHR(48))
               ELSE split_part(BTRIM(i.account_code), CHR(92), 1)
           END AS client_code,
           CASE WHEN POSITION(CHR(92) IN BTRIM(i.account_code)) > 0
                THEN SUBSTRING(BTRIM(i.account_code) FROM POSITION(CHR(92) IN BTRIM(i.account_code)) + 1)
           END AS department_code
    FROM inventory_items i
), resolved AS (
    SELECT p.id, p.raw_code, p.client_code, c.id AS client_id,
           COALESCE(direct.id, prefixed.id) AS department_id
    FROM parsed p
    JOIN clients c ON c.code = p.client_code
    LEFT JOIN departaments direct
      ON direct.client_id = c.id
     AND direct.department_code = p.department_code
    LEFT JOIN departaments prefixed
      ON direct.id IS NULL
     AND prefixed.client_id = c.id
     AND prefixed.department_code = CASE
         WHEN LEFT(p.department_code, LENGTH(c.code) + 1) = c.code || '-'
         THEN SUBSTRING(p.department_code FROM LENGTH(c.code) + 2)
         ELSE p.department_code
     END
)
UPDATE inventory_items i
SET account_code = resolved.client_code,
    client_id = resolved.client_id,
    department_id = COALESCE(resolved.department_id, i.department_id)
FROM resolved
WHERE i.id = resolved.id
  AND resolved.client_code <> ''
  AND (
      i.account_code IS DISTINCT FROM resolved.client_code
      OR i.client_id IS DISTINCT FROM resolved.client_id
      OR i.department_id IS DISTINCT FROM COALESCE(resolved.department_id, i.department_id)
  );

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'inventory_items'::regclass
          AND conname = 'inventory_items_department_client_fkey'
    ) THEN
        ALTER TABLE inventory_items
            ADD CONSTRAINT inventory_items_department_client_fkey
            FOREIGN KEY (department_id, client_id)
            REFERENCES departaments (id, client_id);
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'inventory_items'::regclass
          AND conname = 'inventory_items_department_requires_client'
    ) THEN
        ALTER TABLE inventory_items
            ADD CONSTRAINT inventory_items_department_requires_client
            CHECK (department_id IS NULL OR client_id IS NOT NULL);
    END IF;
END $$;

