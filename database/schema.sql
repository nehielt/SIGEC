CREATE TABLE IF NOT EXISTS inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id VARCHAR(100) NOT NULL UNIQUE,
    item_code VARCHAR(120) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    account_code VARCHAR(120) NOT NULL DEFAULT '',
    account_name VARCHAR(250) NOT NULL DEFAULT '',
    client_id BIGINT REFERENCES clients(id),
    department_id BIGINT,
    alternate_code VARCHAR(120) NOT NULL DEFAULT '',
    location_id BIGINT REFERENCES warehouse_locations(id),
    status VARCHAR(24) NOT NULL DEFAULT 'in'
        CHECK (status IN ('in', 'out', 'permanent_out')),
    permitted BOOLEAN NOT NULL DEFAULT FALSE,
    added_date DATE,
    status_date DATE,
    updated_date DATE,
    status_time VARCHAR(40) NOT NULL DEFAULT '',
    source_sheet VARCHAR(80) NOT NULL DEFAULT 'MANUAL',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ NULL
);

