UPDATE departaments d
SET name = department_names.name
FROM (
    SELECT i.client_id,
           SUBSTRING(BTRIM(i.account_code) FROM POSITION(CHR(92) IN BTRIM(i.account_code)) + 1) AS department_code,
           MAX(BTRIM(i.account_name)) AS name
    FROM inventory_items i
    WHERE POSITION(CHR(92) IN BTRIM(i.account_code)) > 0
      AND BTRIM(i.account_name) <> ''
    GROUP BY i.client_id,
             SUBSTRING(BTRIM(i.account_code) FROM POSITION(CHR(92) IN BTRIM(i.account_code)) + 1)
) AS department_names
WHERE d.client_id = department_names.client_id
  AND d.department_code = department_names.department_code
  AND d.name IS DISTINCT FROM department_names.name;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM inventory_items i
        WHERE POSITION(CHR(92) IN BTRIM(i.account_code)) > 0
          AND NOT EXISTS (
              SELECT 1
              FROM clients c
              WHERE c.code = CASE
                  WHEN LENGTH(split_part(BTRIM(i.account_code), CHR(92), 1)) < 4
                  THEN LPAD(split_part(BTRIM(i.account_code), CHR(92), 1), 4, CHR(48))
